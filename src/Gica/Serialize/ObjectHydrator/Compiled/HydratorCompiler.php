namespace Gica\Serialize\ObjectHydrator\Compiled;

use Gica\Serialize\ObjectHydrator\ObjectHydrator;

/**
 * Generates, once and ahead of time, a hydrator function for a class: the same decisions ObjectHydrator takes by reflection for every property of every object
 * (the cast, the class of the value, list or not, nullable or not) are taken here and written as straight PHP assignments. At run time there is no reflection;
 * a nested object, a value that names its class itself (`@classes`) and every adapter (ids, dates, enums, ...) still go through ObjectHydrator::hydrateObject(),
 * so the result is exactly the one of the reflection path (tests compare them).
 *
 * A property is set by a function bound to the class that DECLARES it (so private and readonly properties of ancestors work); one such function per declaring class.
 * A class is NOT compiled (the reflection path keeps serving it) when it cannot be written safely: abstract/interface/enum/trait, an internal class, a union or
 * intersection type.
 */
class HydratorCompiler
{
    /** change it when the generated code changes: every generated file becomes stale */
    private const VERSION = 1;

    /**
     * @param bool $standardFactories the hydrator's unserializer tries the static factories `fromPrimitive` (scalar or array values) and then `fromString` (strings and
     *                                Stringables) FIRST, like FromPrimitive and FromString do: ids and other value objects with such a factory are then built by a direct call
     *                                (same precedence, same arguments) instead of going through the adapters on every value. Leave it false for any other configuration.
     */
    public function __construct(private readonly ObjectHydrator $hydrator, private readonly bool $standardFactories = false)
    {
    }

    /** @return string|null the PHP source of the generated file, or null with the reason in $why */
    public function compile(string $class, ?string &$why = null): ?string
    {
        $why = $this->whyNotCompilable($class);
        if (null !== $why) {
            return null;
        }
        $rc = new \ReflectionClass($class);
        $groups = $this->propertiesByDeclaringClass($rc);
        $header = "<?php\n"
            . '// generated by ' . self::class . ' for ' . $class . " - do not edit, run the generator again\n"
            . '// signature: ' . $this->signature($class) . "\n";
        $preamble = "    \$a = \\" . ObjectHydrator::class . "::documentToArray(\$d);\n"
            . "    \$k = \$a['@classes'] ?? null;\n";
        $hydrator = '\\' . ObjectHydrator::class;
        if (count($groups) === 1) {
            $declaring = array_key_first($groups);
            return $header . "return \\Closure::bind(static function ($hydrator \$h, object \$o, \$d): void {\n" . $preamble
                . $this->properties($rc, $groups[$declaring]) . '}, null, ' . var_export($declaring, true) . ");\n";
        }
        $parts = '';
        foreach ($groups as $declaring => $properties) {
            $parts .= "    \\Closure::bind(static function ($hydrator \$h, object \$o, array \$a, \$k): void {\n"
                . $this->properties($rc, $properties) . '    }, null, ' . var_export($declaring, true) . "),\n";
        }
        return $header . "\$parts = [\n$parts];\n"
            . "return static function ($hydrator \$h, object \$o, \$d) use (\$parts): void {\n" . $preamble
            . "    foreach (\$parts as \$part) {\n        \$part(\$h, \$o, \$a, \$k);\n    }\n};\n";
    }

    /**
     * Every settable property once, by the class that declares it, the most derived declaration first (the one the reflection path finds first).
     * @return array<string, \ReflectionProperty[]>
     */
    private function propertiesByDeclaringClass(\ReflectionClass $rc): array
    {
        $groups = [];
        $taken = [];
        for ($c = $rc; $c; $c = $c->getParentClass()) {
            foreach ($c->getProperties() as $property) {
                if ($property->isStatic() || $property->getDeclaringClass()->getName() !== $c->getName() || isset($taken[$property->getName()])) {
                    continue;
                }
                $taken[$property->getName()] = true;
                $groups[$c->getName()][] = $property;
            }
        }
        return $groups;
    }

    /** @param \ReflectionProperty[] $properties */
    private function properties(\ReflectionClass $rc, array $properties): string
    {
        $body = '';
        foreach ($properties as $property) {
            $body .= $this->property($rc, $property);
        }
        return $body;
    }

    /** the classes whose objects this class can contain (to compile them too) */
    public function referencedClasses(string $class): array
    {
        $rc = new \ReflectionClass($class);
        $found = [];
        foreach ($this->propertiesByDeclaringClass($rc) as $properties) {
            foreach ($properties as $property) {
                try {
                    $plan = $this->hydrator->planForCompiler($rc, $property->getName());
                } catch (\Throwable) {
                    continue;
                }
                if (null !== $plan[1] && class_exists($plan[1])) {
                    $found[$plan[1]] = true;
                }
            }
        }
        return array_keys($found);
    }

    /** hash of the source of the class, of its ancestors and traits, and of this generator: a generated file with another one is stale */
    public function signature(string $class): string
    {
        $rc = new \ReflectionClass($class);
        $parts = ['v' . self::VERSION];
        for ($c = $rc; $c; $c = $c->getParentClass()) {
            $parts[] = $c->getName() . ':' . ($c->getFileName() ? md5_file($c->getFileName()) : '');
            foreach ($c->getTraits() as $trait) {
                $parts[] = $trait->getName() . ':' . ($trait->getFileName() ? md5_file($trait->getFileName()) : '');
            }
        }
        return md5(implode('|', $parts));
    }

    /**
     * Writes one file per class and the index. Existing files that are not in the new list are removed by the caller (see the generator script).
     * @param string[] $classes
     * @return array{compiled: string[], skipped: array<string, string>}
     */
    public function writeDirectory(string $directory, array $classes): array
    {
        if (!is_dir($directory) && !mkdir($directory, 0775, true) && !is_dir($directory)) {
            throw new \RuntimeException("cannot create $directory");
        }
        $index = [];
        $skipped = [];
        foreach (array_unique($classes) as $class) {
            $source = $this->compile($class, $why);
            if (null === $source) {
                $skipped[$class] = (string)$why;
                continue;
            }
            $file = 'h_' . md5($class) . '.php';
            $this->writeAtomically($directory . '/' . $file, $source);
            $index[$class] = $file;
        }
        ksort($index);
        $this->writeAtomically($directory . '/index.php', "<?php\n// generated, do not edit\nreturn " . var_export($index, true) . ";\n");
        return ['compiled' => array_keys($index), 'skipped' => $skipped];
    }

    private function writeAtomically(string $file, string $content): void
    {
        $tmp = $file . '.' . getmypid() . '.tmp';
        file_put_contents($tmp, $content);
        rename($tmp, $file);
    }

    private function whyNotCompilable(string $class): ?string
    {
        if (!class_exists($class)) {
            return 'not a class';
        }
        $rc = new \ReflectionClass($class);
        if ($rc->isAbstract() || $rc->isInterface() || $rc->isEnum() || $rc->isTrait()) {
            return 'abstract, interface, enum or trait';
        }
        if ($rc->isInternal()) {
            return 'internal class';
        }
        foreach ($this->propertiesByDeclaringClass($rc) as $properties) {
            foreach ($properties as $property) {
                if ($property->hasType() && !($property->getType() instanceof \ReflectionNamedType)) {
                    return 'union or intersection type on ' . $property->getName();
                }
            }
        }
        return null;
    }

    private function property(\ReflectionClass $rc, \ReflectionProperty $property): string
    {
        $name = $property->getName();
        $key = var_export($name, true);
        [$builtin, $class, $isList, $isListByComment] = $this->hydrator->planForCompiler($rc, $name);
        $nullable = !$property->hasType() || $property->getType()->allowsNull();

        $generic = fn(string $in, string $out) => "$out = \$h->hydrateObject(\$hint, $in);";
        $hinted = $isListByComment
            ? '$r = []; foreach ($v as $i => $item) { ' . $generic('$item', '$r[$i]') . ' }'
            : $generic('$v', '$r');
        if (null !== $class && $isListByComment === $isList) {
            // the document names the class of the value (`@classes`): when it is the declared one, which is nearly always, the inlined build applies
            $same = $isListByComment ? '$r = []; foreach ($v as $i => $item) { ' . $this->value($class, '$item', '$r[$i]') . ' }' : $this->value($class, '$v', '$r');
            $hinted = 'if ($hint === ' . var_export($class, true) . ") {\n                    $same\n                } else {\n                    $hinted\n                }";
        }
        $plain = $this->plain($builtin, $class, $isList);
        $assign = $nullable ? "\$o->$name = \$r;" : "if (null !== \$r) { \$o->$name = \$r; }";

        return "    if (\\array_key_exists($key, \$a)) {\n"
            . "        try {\n"
            . "            \$v = \$a[$key];\n"
            . "            if (null === \$v) {\n"
            . "                \$r = null;\n"
            . "            } elseif (\$k && isset(\$k[$key]) && (\$hint = \$k[$key])) {\n"
            . "                $hinted\n"
            . "            } else {\n"
            . "                $plain\n"
            . "            }\n"
            . "            $assign\n"
            . "        } catch (\\Exception) {\n"
            . "        }\n"
            . "    }\n";
    }

    private function plain(?string $builtin, ?string $class, bool $isList): string
    {
        if (null !== $builtin) {
            return '$r = ' . $this->cast($builtin, '$v') . ';';
        }
        if (null === $class) {
            return '$r = $v;';
        }
        return $isList
            ? '$r = []; foreach ($v as $i => $item) { ' . $this->value($class, '$item', '$r[$i]') . ' }'
            : $this->value($class, '$v', '$r');
    }

    /** PHP code that assigns to $out the object of class $class built from the document value $in (exactly what ObjectHydrator::hydrateObject() returns) */
    private function value(string $class, string $in, string $out): string
    {
        $c = var_export($class, true);
        if (in_array($class, ['string', 'mixed', 'int', 'float', 'bool', 'boolean', 'null'], true)) {
            return "$out = " . $this->cast($class, $in) . ';';
        }
        $generic = "$out = \$h->hydrateObject($c, $in);";
        if (!$this->standardFactories || !class_exists($class)) {
            return $generic;
        }
        $fromPrimitive = is_callable([$class, 'fromPrimitive']);
        $fromString = is_callable([$class, 'fromString']);
        if (!$fromPrimitive && !$fromString) {
            return $generic;
        }
        $code = '';
        if ($fromPrimitive) {
            $code .= "if (\\is_scalar($in) || \\is_array($in)) { $out = \\$class::fromPrimitive($in); } else";
        }
        if ($fromString) {
            $code .= ($fromPrimitive ? 'if' : 'if') . "(\\is_string($in) || $in instanceof \\Stringable) { $out = \\$class::fromString((string)$in); } else";
        }
        return $code . " { $generic }";
    }

    private function cast(string $builtin, string $v): string
    {
        return match ($builtin) {
            'string' => "\\strval($v)",
            'mixed' => $v,
            'int' => "(\\is_int($v) ? $v : (\\is_string($v) && $v === (string)((int)$v) ? (int)$v : null))",
            'float' => "\\floatval($v)",
            'bool', 'boolean' => "(\\is_bool($v) ? $v : ($v === '1' || $v === 'true' ? true : ($v === '0' || $v === 'false' ? false : null)))",
            'null' => 'null',
        };
    }
}
