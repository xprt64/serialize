namespace Gica\Serialize\ObjectHydrator\Mapped;

use Gica\Serialize\ObjectHydrator\ObjectHydrator;

/**
 * Builds, once and ahead of time, the hydration map of a class (see ClassMaps): the decisions ObjectHydrator takes by reflection for every property of every object
 * (cast, class of the value, list or not, nullable or not, who declares the property) written as plain data, one line per property, that a person can read and review.
 *
 * A class is NOT mapped (the reflection path keeps serving it) when a map would not be safe: abstract/interface/enum/trait, an internal class, a union or intersection type.
 */
class ClassMapBuilder
{
    /** change it when the format or the decisions change: every map becomes stale */
    private const VERSION = 1;

    /**
     * @param bool $standardFactories the hydrator's unserializer tries the static factories `fromPrimitive` (scalar or array values) and then `fromString` (strings and
     *                                Stringables) first, like FromPrimitive and FromString: classes with such a factory are then built by a direct call (the `from` key).
     *                                Leave it false for any other configuration.
     */
    public function __construct(private readonly ObjectHydrator $hydrator, private readonly bool $standardFactories = false)
    {
    }

    /** @return array<string, array<string, mixed>>|null the map, or null with the reason in $why */
    public function build(string $class, ?string &$why = null): ?array
    {
        $why = $this->whyNotMappable($class);
        if (null !== $why) {
            return null;
        }
        $rc = new \ReflectionClass($class);
        $map = [];
        foreach ($this->propertiesByDeclaringClass($rc) as $declaring => $properties) {
            foreach ($properties as $property) {
                $map[$property->getName()] = $this->entry($rc, $property, $declaring === $class ? null : $declaring);
            }
        }
        return $map;
    }

    /** @return string[] the classes whose objects this class can contain (to map them too) */
    public function referencedClasses(string $class): array
    {
        $rc = new \ReflectionClass($class);
        $found = [];
        foreach ($this->propertiesByDeclaringClass($rc) as $properties) {
            foreach ($properties as $property) {
                try {
                    $plan = $this->hydrator->planForCompiler($rc, $property->getName());
                } catch (\Throwable) {
                    continue;
                }
                if (null !== $plan[1] && class_exists($plan[1])) {
                    $found[$plan[1]] = true;
                }
            }
        }
        return array_keys($found);
    }

    /** hash of the source of the class, of its ancestors and traits, and of this builder: a map with another one is stale */
    public function signature(string $class): string
    {
        $rc = new \ReflectionClass($class);
        $parts = ['v' . self::VERSION, $this->standardFactories ? 'factories' : 'plain'];
        for ($c = $rc; $c; $c = $c->getParentClass()) {
            $parts[] = $c->getName() . ':' . ($c->getFileName() ? md5_file($c->getFileName()) : '');
            foreach ($c->getTraits() as $trait) {
                $parts[] = $trait->getName() . ':' . ($trait->getFileName() ? md5_file($trait->getFileName()) : '');
            }
        }
        return md5(implode('|', $parts));
    }

    /**
     * The PHP file for PhpFileClassMaps: one array literal, one line per property, and the signature of every class in a comment (to find a stale map without loading anything).
     * @param string[] $classes
     * @return array{source: string, mapped: string[], skipped: array<string, string>}
     */
    public function export(array $classes): array
    {
        $classes = array_unique($classes);
        sort($classes);
        $body = '';
        $mapped = [];
        $skipped = [];
        foreach ($classes as $class) {
            $map = $this->build($class, $why);
            if (null === $map) {
                $skipped[$class] = (string)$why;
                continue;
            }
            $mapped[] = $class;
            $body .= "\n    // signature " . $this->signature($class) . "\n    " . var_export($class, true) . " => [\n";
            foreach ($map as $name => $entry) {
                $body .= '        ' . var_export($name, true) . ' => ' . $this->line($entry) . ",\n";
            }
            $body .= "    ],\n";
        }
        return [
            'source' => "<?php\n// Hydration maps, generated by " . self::class . " - do not edit, run the generator again.\n// Read by " . PhpFileClassMaps::class . "; the format is described in " . ClassMaps::class . ".\n\nreturn [" . $body . "];\n",
            'mapped' => $mapped,
            'skipped' => $skipped,
        ];
    }

    /** the signatures written by export(): class => signature */
    public static function signaturesIn(string $source): array
    {
        preg_match_all("~// signature ([0-9a-f]{32})\n    ('[^\n]*') => \\[~", $source, $m, PREG_SET_ORDER);
        $result = [];
        foreach ($m as $row) {
            $result[str_replace(['\\\\', "\\'"], ['\\', "'"], substr($row[2], 1, -1))] = $row[1];
        }
        return $result;
    }

    private function line(array $entry): string
    {
        $parts = [];
        foreach ($entry as $key => $value) {
            $parts[] = var_export($key, true) . ' => ' . (is_array($value) ? '[' . implode(', ', array_map(fn($v) => var_export($v, true), $value)) . ']' : var_export($value, true));
        }
        return '[' . implode(', ', $parts) . ']';
    }

    private function entry(\ReflectionClass $rc, \ReflectionProperty $property, ?string $declaring): array
    {
        [$builtin, $class, $isList, $isListByDocblock] = $this->hydrator->planForCompiler($rc, $property->getName());
        $entry = [];
        if (null !== $builtin) {
            $entry['type'] = $builtin;
        }
        if (null !== $class && \in_array($class, ['string', 'mixed', 'int', 'float', 'bool', 'boolean', 'null'], true)) {
            $entry['type'] = $class; // a value (or the items of a list) of a builtin type: cast, no class
            $class = null;
        }
        if (null !== $class) {
            $entry['class'] = $class;
        }
        if ($isList) {
            $entry['list'] = true;
        }
        if ($isListByDocblock) {
            $entry['listDoc'] = true;
        }
        if (!$property->hasType() || $property->getType()->allowsNull()) {
            $entry['null'] = true;
        }
        if (null !== $declaring) {
            $entry['in'] = $declaring;
        }
        if (null !== $class && $this->standardFactories && ($from = $this->factories($class))) {
            $entry['from'] = $from;
        }
        return $entry;
    }

    /** @return string[] */
    private function factories(string $class): array
    {
        if (in_array($class, ['string', 'mixed', 'int', 'float', 'bool', 'boolean', 'null'], true) || !class_exists($class)) {
            return [];
        }
        $from = [];
        if (is_callable([$class, 'fromPrimitive'])) {
            $from[] = 'primitive';
        }
        if (is_callable([$class, 'fromString'])) {
            $from[] = 'string';
        }
        return $from;
    }

    /**
     * Every settable property once, by the class that declares it, the most derived declaration first (the one the reflection path finds first).
     * @return array<string, \ReflectionProperty[]>
     */
    private function propertiesByDeclaringClass(\ReflectionClass $rc): array
    {
        $groups = [];
        $taken = [];
        for ($c = $rc; $c; $c = $c->getParentClass()) {
            foreach ($c->getProperties() as $property) {
                if ($property->isStatic() || $property->getDeclaringClass()->getName() !== $c->getName() || isset($taken[$property->getName()])) {
                    continue;
                }
                $taken[$property->getName()] = true;
                $groups[$c->getName()][] = $property;
            }
        }
        return $groups;
    }

    private function whyNotMappable(string $class): ?string
    {
        if (!class_exists($class)) {
            return 'not a class';
        }
        $rc = new \ReflectionClass($class);
        if ($rc->isAbstract() || $rc->isInterface() || $rc->isEnum() || $rc->isTrait()) {
            return 'abstract, interface, enum or trait';
        }
        if ($rc->isInternal()) {
            return 'internal class';
        }
        foreach ($this->propertiesByDeclaringClass($rc) as $properties) {
            foreach ($properties as $property) {
                if ($property->hasType() && !($property->getType() instanceof \ReflectionNamedType)) {
                    return 'union or intersection type on ' . $property->getName();
                }
            }
        }
        return null;
    }
}
